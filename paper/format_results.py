"""Typeset the manuscript's estimates and tables from the aggregate evaluation files."""
from collections import defaultdict
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_json(path):
    return json.loads((ROOT / path).read_text())


def main():
    repeated = read_json("validation/repeated-patient-cv/repeat_results.json")
    fixed = read_json("validation/patient-grouped-deeptcr/aggregate_results.json")
    chains = read_json("validation/source-cohort/composition-sensitivity.json")
    if repeated["completed_fits"] != 57 or fixed["status"] != "complete" or len(fixed["folds"]) != 5:
        raise ValueError("Full repeated and fixed-partition aggregates are required")
    primary = defaultdict(list)
    sensitivity = {}
    for result in repeated["runs"]:
        if result["folds"] == 5:
            primary[result["partition_seed"]].append(result)
        else:
            sensitivity[result["folds"]] = result
    stats = repeated["summary"]
    study = stats["deeptcr_within_fold"]
    base = stats["baseline_within_fold"]
    control = fixed["shuffled_training_control"]
    ci = fixed["within_fold_patient_auroc_bootstrap_ci95"]
    estimates = {
        "DeepMedian": study["median"], "DeepLow": study["minimum"], "DeepHigh": study["maximum"],
        "BaseMedian": base["median"], "BaseLow": base["minimum"], "BaseHigh": base["maximum"],
        "ThreeDeep": sensitivity[3]["deeptcr"]["within_fold_auroc"],
        "ThreeBase": sensitivity[3]["composition"]["within_fold_auroc"],
        "FourDeep": sensitivity[4]["deeptcr"]["within_fold_auroc"],
        "FourBase": sensitivity[4]["composition"]["within_fold_auroc"],
        "FixedAUC": fixed["within_fold_patient_auroc"], "CILow": ci[0], "CIHigh": ci[1],
        "PooledAUC": fixed["pooled_oof_patient_auroc"],
        "AvgPrecision": fixed["pooled_oof_patient_average_precision"],
        "ShuffleAUC": control["patient_auroc"],
        "ControlTrueAUC": fixed["folds"][control["fold"] - 1]["patient_auroc"],
    }
    macros = {key: f"{v:.3f}" for key, v in estimates.items()}
    macros.update(Above=stats["deeptcr_above_baseline"], Below=stats["baseline_above_deeptcr"],
                  Ties=stats["ties"], FixedWins=f"{fixed['patient_pairs_concordant_ties_half']:g}",
                  FixedPairs=fixed["patient_pairs"], NumCorrect=fixed["correct_at_threshold_0_5"],
                  PermutationHits=f"{fixed['fixed_score_shuffles_at_least_as_high']:,}")
    primary_rows = []
    for i, seed in enumerate(sorted(primary), 1):
        first, second = sorted(primary[seed], key=lambda r: r["training_seed"])
        if first["composition"] != second["composition"]:
            raise ValueError("Matched baseline differs between training seeds")
        aucs = [first["deeptcr"]["within_fold_auroc"], second["deeptcr"]["within_fold_auroc"],
                first["composition"]["within_fold_auroc"]]
        primary_rows.append(" & ".join([str(i), *(f"{value:.3f}" for value in aucs)]))
    fixed_rows = []
    for row in fixed["folds"]:
        fixed_rows.append(" & ".join([str(row[k]) for k in ("fold", "train_patients", "test_patients", "test_positive_patients")] +
                                     [f"{row['test_rows']:,}", f"{row['patient_auroc']:.3f}"]))
    chain_rows = []
    for key, name in [("archived_pair_rows", "Pair rows"), ("paired_cells", "Beta, paired cells"),
                      ("all_beta", "Beta, all cells")]:
        unit = chains[key]
        runs = sorted((x for x in unit["runs"] if x["folds"] == 5), key=lambda x: x["partition_seed"])
        if [x["partition_seed"] for x in runs] != sorted(primary):
            raise ValueError("Chain comparison uses different partitions")
        chain_rows.append(" & ".join([name, f"{unit['rows']:,}", *(f"{x['within_fold_auroc']:.3f}" for x in runs),
                                      f"{unit['primary_median_within_fold_auroc']:.3f}"]))
    for name, rows in [("PrimaryRows", primary_rows), ("FixedRows", fixed_rows), ("ChainRows", chain_rows)]:
        macros[name] = "\n" + "\n".join(row + r" \\" for row in rows) + "\n"
    output = ["% Generated by paper/format_results.py from the aggregate study results."]
    output.extend("\\newcommand{\\" + key + "}{" + str(value) + "}" for key, value in macros.items())
    (ROOT / "paper/study-values.tex").write_text("\n".join(output) + "\n")


if __name__ == "__main__":
    main()
